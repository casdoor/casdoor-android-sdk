package org.casdoor

import com.squareup.moshi.Moshi
import com.squareup.moshi.Types
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull
import okhttp3.OkHttpClient
import okhttp3.Request
import okio.IOException
import java.lang.reflect.Type

/**
 * Casdoor client. All methods except getSignInUrl() and getSignUpUrl() make blocking network calls,
 * so do not call them on the main thread.
 */
class Casdoor(private val config: CasdoorConfig) {
    /**
     * PKCE code verifier generated by the last getSignInUrl() call. Save it (for example in
     * onSaveInstanceState) if the activity may be recreated before the redirect comes back,
     * and pass it to requestOauthAccessToken().
     */
    var codeVerifier: String? = null
        private set
    private var nonce: String? = null

    private val client = OkHttpClient()
    private val moshi = Moshi.Builder().build()

    // Moshi adapters
    private val accessTokenResponseAdaptor = moshi.adapter(AccessTokenResponse::class.java)
    private val casdoorResponseType: Type = Types.newParameterizedType(
        CasdoorResponse::class.java,
        String::class.java,
        String::class.java
    )
    private val casdoorNoDataResponseAdaptor =
        moshi.adapter<CasdoorResponse<String, String>>(casdoorResponseType)
    private val userInfoAdaptor = moshi.adapter(UserInfo::class.java)

    /**
     * Get the sign in URL.
     */
    @JvmOverloads
    fun getSignInUrl(scope: String? = null, state: String? = null): String {
        this.codeVerifier = Utils.generateCodeVerifier()
        val url = "${config.endpoint}/login/oauth/authorize"
        this.nonce = Utils.generateNonce()
        val query = CodeRequestQuery(
            config = config,
            nonce = nonce!!,
            scope = scope,
            state = state,
            codeVerifier = codeVerifier!!
        )

        val httpUrl = url.toHttpUrlOrNull()

        httpUrl ?: throw IllegalArgumentException("Invalid URL")

        return query.toHttpUrl(httpUrl).toString()
    }

    /**
     * Get the sign up URL.
     */
    @JvmOverloads
    fun getSignUpUrl(scope: String? = null, state: String? = null): String {
        val urlString =
            getSignInUrl(scope, state).replace("/login/oauth/authorize", "/signup/oauth/authorize")
        return urlString.toHttpUrlOrNull()?.toString()
            ?: throw IllegalArgumentException("Invalid URL")
    }

    /**
     * Get Access Token.
     *
     * @param codeVerifier the verifier of the getSignInUrl() call that started this sign in,
     * defaults to the one kept by this instance.
     */
    @JvmOverloads
    fun requestOauthAccessToken(
        code: String,
        codeVerifier: String? = this.codeVerifier
    ): AccessTokenResponse {
        val httpUrl = "${config.endpoint}/api/login/oauth/access_token".toHttpUrlOrNull()
        httpUrl ?: throw IllegalArgumentException("Invalid URL")
        val body = AccessTokenRequest(
            code = code,
            verifier = codeVerifier
                ?: throw IllegalStateException("Please call getSignInUrl first"),
            clientID = config.clientID
        ).toFormBody()

        return requestToken(Request.Builder().url(httpUrl).post(body).build())
    }

    /**
     * Renew Access Token.
     */
    @JvmOverloads
    fun renewToken(refreshToken: String, scope: String? = null): AccessTokenResponse {
        val httpUrl = "${config.endpoint}/api/login/oauth/refresh_token".toHttpUrlOrNull()
        httpUrl ?: throw IllegalArgumentException("Invalid URL")
        val body = RenewAccessTokenRequest(
            refreshToken = refreshToken,
            scope = scope ?: "read",
            clientID = config.clientID
        ).toFormBody()

        return requestToken(Request.Builder().url(httpUrl).post(body).build())
    }

    private fun requestToken(request: Request): AccessTokenResponse {
        client.newCall(request).execute().use {
            // Casdoor returns OAuth errors such as invalid_grant with HTTP 400 and a JSON body
            val accessToken: AccessTokenResponse? = try {
                accessTokenResponseAdaptor.fromJson(it.body!!.source())
            } catch (e: Exception) {
                throw IOException(if (it.isSuccessful) "response error: $it" else "Unexpected code $it", e)
            }
            if (accessToken?.error != null) {
                throw IOException("${accessToken.error}: ${accessToken.errorDescription}")
            }
            if (!it.isSuccessful) throw IOException("Unexpected code $it")
            accessToken?.accessToken ?: throw IOException("response error: $it")
            return accessToken
        }
    }

    /**
     * Logout.
     */
    @JvmOverloads
    fun logout(idToken: String, state: String? = null): Boolean {
        var httpUrl = "${config.endpoint}/api/logout".toHttpUrlOrNull()
        httpUrl ?: throw IllegalArgumentException("Invalid URL")
        httpUrl = httpUrl.newBuilder()
            .addQueryParameter("id_token_hint", idToken)
            .addQueryParameter("state", state ?: config.appName)
            .build()

        client.newCall(Request.Builder().url(httpUrl).get().build()).execute().use {
            if (!it.isSuccessful) throw IOException("Unexpected code $it")

            try {
                val casdoorResponse: CasdoorNoDataResponse? =
                    casdoorNoDataResponseAdaptor.fromJson(it.body!!.source())
                if (casdoorResponse?.isSuccessful() == false) {
                    throw IOException("response error: $it")
                }

                val isAffected = casdoorResponse?.data
                return (isAffected != null && isAffected == "Affected")
            } catch (e: Exception) {
                throw IOException("response error: $it")
            }

        }
    }

    /**
     * Get user info.
     */
    fun getUserInfo(idToken: String): UserInfo? {
        val request = Request.Builder()
            .url("${config.endpoint}/api/userinfo?scope=profile")
            .header("Authorization", "Bearer $idToken")
            .build();

        client.newCall(request).execute().use {
            if (!it.isSuccessful) throw IOException("Unexpected code $it")

            try {
                return userInfoAdaptor.fromJson(it.body!!.source())
            } catch (e: Exception) {
                throw IOException("response error: $it")
            }
        }
    }
}
